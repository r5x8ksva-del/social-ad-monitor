const NEGATED = /(非|不是|无|没有|绝无|拒绝|不接)(任何)?(广告|恰饭|推广|合作|赞助)/g;

// 披露程度：看标题、简介、置顶评论、口播里的原话（去掉「绝无恰饭」这类否定句再判断）
export function disclosureLevel(texts) {
  const joined = texts.filter(Boolean).join('\n').replace(NEGATED, '');
  if (/广告/.test(joined)) return '明示广告';
  if (/赞助|合作|推广|恰饭|商单|金主/.test(joined)) return '提到赞助合作';
  return '无';
}
